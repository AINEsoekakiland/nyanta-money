export function getEpisodeBySlug(slug: string): Episode | undefined {
  return episodes.find((ep) => ep.slug === slug);
}

export function getRelatedEpisodes(slug: string, count = 3): Episode[] {
  return episodes.filter((ep) => ep.slug !== slug).slice(0, count);
}

export function getPopularEpisodes(count = 3): Episode[] {
  return episodes.filter((ep) => ep.popular).slice(0, count);
}
